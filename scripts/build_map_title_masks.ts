function titlePixels(image: RgbaImage): { pixels: Rgb[]; width: number; height: number } {
  const x = Math.max(0, Math.round(DRAFT_TITLE_BOX.x * image.width));
  const y = Math.max(0, Math.round(DRAFT_TITLE_BOX.y * image.height));
  const width = Math.max(1, Math.min(image.width - x, Math.round(DRAFT_TITLE_BOX.w * image.width)));
  const height = Math.max(1, Math.min(image.height - y, Math.round(DRAFT_TITLE_BOX.h * image.height)));
  const pixels: Rgb[] = [];
  for (let row = 0; row < height; row++) {
    for (let col = 0; col < width; col++) {
      const i = ((y + row) * image.width + (x + col)) * 4;
      pixels.push({
        r: image.data[i] ?? 0,
        g: image.data[i + 1] ?? 0,
        b: image.data[i + 2] ?? 0,
      });
    }
  }
  return { pixels, width, height };
}

const lines = [
  "/** Saved map-title glyphs from examples/drafts. Regenerated by scripts/build_map_title_masks.ts. */",
  "",
  "export const MAP_TITLE_MASKS: readonly { map: string; bits: string }[] = [",
];
for (const label of LABELS) {
  const image = decodePng(
    readFileSync(path.join(process.cwd(), "examples", "drafts", label.file)),
  );
  const title = titlePixels(image);
  const mask = titleGlyphMask(title.pixels, title.width, title.height);
  let bits = "";
  for (let i = 0; i < mask.length; i++) bits += mask[i] ? "1" : "0";
  lines.push(`  { map: ${JSON.stringify(label.map)}, bits: ${JSON.stringify(bits)} },`);
}
lines.push("];", "");
writeFileSync(
  path.join(process.cwd(), "src", "lib", "lobby", "mapTitleMasks.ts"),
  lines.join("\n"),
  "utf8",
);
console.log(`wrote ${LABELS.length} masks`);
